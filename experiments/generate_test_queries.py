"""
生成大规模测试查询（100+ 条）用于论文对比实验。

数据来源：security_monitor.db
策略：基于真实 DB schema 和分析结果，生成 10 大类查询，
      覆盖一级（直接复用）、二级（编辑复用）、三级（全新）链路。
"""

import random
import json
import os

random.seed(42)

# ========== 基础素材 ==========

DEVICE_TYPES = ["camera", "vibration fiber", "electronic pulse sensor"]
DEVICE_TYPES_CN = ["摄像头", "振动光纤", "电子脉冲"]

REGIONS = ["Area A", "Area B", "Area C", "Area D", "Area E",
           "Perimeter", "Main Building", "Parking Lot", "Warehouse", "Equipment Area"]

ALARM_TYPES = ["area intrusion", "abnormal intrusion", "cross-border alarm",
               "zone alarm", "vibration fiber event"]


def build_queries():
    queries = set()

    # === 1. Online Rate ===
    templates_online = [
        "What is the online rate of {device}s?",
        "Compare the online rate of {d1}s and {d2}s",
        "Show the online rate of {device}s in {region}",
        "What is the online rate of {device}s deployed in {region}?",
        "List the online status of all {device} devices",
    ]
    for dt in DEVICE_TYPES:
        queries.add(templates_online[0].format(device=dt))
        queries.add(templates_online[4].format(device=dt))
        for region in ["Area A", "Area B", "Perimeter", "Main Building"]:
            queries.add(templates_online[2].format(device=dt, region=region))
            queries.add(templates_online[3].format(device=dt, region=region))
    for i, d1 in enumerate(DEVICE_TYPES):
        for d2 in DEVICE_TYPES[i+1:]:
            queries.add(templates_online[1].format(d1=d1, d2=d2))
    queries.add("What is the overall online rate of security devices?")
    queries.add("Show me the online rate trend by device type")
    queries.add("Which areas have the highest device online rate?")
    queries.add("Which device type has the lowest online rate?")

    # === 2. Alert / Trigger Stats ===
    templates_alert = [
        "Show the triggering count of {device}s",
        "How many alarms were generated by {device}s last month?",
        "What is the total alarm count for {alarm_type}?",
        "List the {alarm_type} events in {region}",
        "Show the alarm distribution by {device} type",
    ]
    for dt in DEVICE_TYPES:
        queries.add(templates_alert[0].format(device=dt))
        queries.add(templates_alert[4].format(device=dt))
    for at in ALARM_TYPES:
        queries.add(templates_alert[2].format(alarm_type=at))
        for region in ["Area A", "Area B", "Perimeter"]:
            queries.add(templates_alert[3].format(alarm_type=at, region=region))
    queries.add("Compare alarm counts across different alarm types")
    queries.add("Which alarm type occurred most frequently?")
    queries.add("What is the hourly distribution of security alarm events?")
    queries.add("Show the alarm events trend over the past month")
    queries.add("List the top 10 most frequent alarm locations")
    queries.add("What is the peak time for security alarm events?")
    queries.add("Show the alarm count per device type for last week")

    # === 3. Offline Analysis ===
    templates_offline = [
        "Which sensors have the most offline occurrences?",
        "List devices that have been offline for more than {h} hours",
        "Which {device}s have the highest offline rate?",
        "Show offline events in {region}",
        "What is the average offline duration per device type?",
    ]
    queries.add(templates_offline[0])
    for h in [2, 6, 12, 24, 48]:
        queries.add(templates_offline[1].format(h=h))
    for dt in DEVICE_TYPES:
        queries.add(templates_offline[2].format(device=dt))
    for region in ["Area A", "Area B", "Area C", "Perimeter"]:
        queries.add(templates_offline[3].format(region=region))
    queries.add(templates_offline[4])
    queries.add("Show the offline ranking of all devices")
    queries.add("Which area has the most offline devices?")

    # === 4. Deployment / Distribution ===
    templates_deploy = [
        "List the sensor distribution by region",
        "How many {device}s are deployed in each region?",
        "Show the deployment density of {device}s across regions",
        "Which region has the most {device}s installed?",
        "What is the installation time distribution of sensors?",
        "List the sensor deployment in the perimeter area",
        "Show devices installed in {month}",
    ]
    queries.add(templates_deploy[0])
    queries.add(templates_deploy[4])
    queries.add(templates_deploy[5])
    for dt in DEVICE_TYPES:
        queries.add(templates_deploy[1].format(device=dt))
        queries.add(templates_deploy[2].format(device=dt))
        queries.add(templates_deploy[3].format(device=dt))
    for month in ["2025-11", "2025-10", "2025-09", "2025-08"]:
        queries.add(templates_deploy[6].format(month=month))

    # === 5. Region-specific ===
    templates_region = [
        "Which sensors are deployed in {region} and what is their online status?",
        "What is the online rate of sensors in {region}?",
        "Show all alarm events in {region} last month",
        "How many {device}s are in {region}?",
        "Compare the alarm frequency between {r1} and {r2}",
    ]
    for r in REGIONS:
        queries.add(templates_region[0].format(region=r))
        queries.add(templates_region[1].format(region=r))
        queries.add(templates_region[2].format(region=r))
        for dt in DEVICE_TYPES:
            queries.add(templates_region[3].format(device=dt, region=r))
    queries.add(templates_region[4].format(r1="Area A", r2="Area B"))
    queries.add("Compare device deployment between perimeter and main building")
    queries.add("Which zone has the highest density of vibration fiber sensors?")
    queries.add("Show the cross-region comparison of alarm event counts")

    # === 6. Top K / Ranking ===
    templates_topk = [
        "What are the top {k} sensors with the lowest online rate?",
        "Show the top {k} devices with most alarm events",
        "List the {k} most frequently triggered {device}s",
        "Which {k} areas have the highest alarm frequency?",
        "Show the top {k} offline devices",
    ]
    for k in [3, 5, 10]:
        queries.add(templates_topk[0].format(k=k))
        queries.add(templates_topk[1].format(k=k))
        queries.add(templates_topk[4].format(k=k))
        for dt in DEVICE_TYPES:
            queries.add(templates_topk[2].format(k=3, device=dt))
            queries.add(templates_topk[2].format(k=5, device=dt))
    queries.add(templates_topk[3].format(k=5))

    # === 7. Alarm Handling ===
    templates_handle = [
        "Show the alarm handling status distribution",
        "How many alarms are still unresolved?",
        "What is the average handling time for {alarm_type}?",
        "Which operator handled the most alarm events?",
        "Show the alarm closure rate by device type",
    ]
    queries.add(templates_handle[0])
    queries.add(templates_handle[1])
    queries.add(templates_handle[4])
    for at in ALARM_TYPES:
        queries.add(templates_handle[2].format(alarm_type=at))
    queries.add(templates_handle[3])

    # === 8. Multi-condition Combined ===
    templates_combined = [
        "Show the {device}s in {region} that were offline more than {n} times",
        "List alarm events for {device}s in {region} last month",
        "Compare online rate of {device}s between {r1} and {r2}",
        "Which {device} in {region} has the highest false alarm rate?",
        "Show the top {k} alarm events by severity in {region}",
    ]
    for dt in DEVICE_TYPES:
        for reg in ["Area A", "Area B", "Perimeter"]:
            queries.add(templates_combined[0].format(device=dt, region=reg, n=3))
            queries.add(templates_combined[1].format(device=dt, region=reg))
            queries.add(templates_combined[3].format(device=dt, region=reg))
    queries.add(templates_combined[2].format(device="cameras", r1="Area A", r2="Area B"))
    queries.add(templates_combined[4].format(k=5, region="Area A"))

    # === 9. Time Series ===
    templates_time = [
        "Show the daily alarm trend for {device}s in November 2025",
        "How many alarms occurred between {t1} and {t2}?",
        "What is the average response time for alarms in {region}?",
        "Compare the alarm frequency between daytime and nighttime",
        "Show the weekly alarm pattern for the past month",
    ]
    for dt in DEVICE_TYPES:
        queries.add(templates_time[0].format(device=dt))
    queries.add(templates_time[1].format(t1="2025-11-01", t2="2025-11-15"))
    queries.add(templates_time[1].format(t1="2025-11-16", t2="2025-11-30"))
    queries.add(templates_time[3])
    queries.add(templates_time[4])
    for r in ["Area A", "Area B", "Perimeter"]:
        queries.add(templates_time[2].format(region=r))

    # === 10. Statistical Comparison ===
    templates_stat = [
        "What is the average triggering frequency of {device}s per day?",
        "Compare the false alarm rates among different sensor types",
        "Show the correlation between device online rate and alarm frequency",
        "Which device type has the most consistent performance?",
        "Analyze the alarm event distribution by time of day",
    ]
    for dt in DEVICE_TYPES:
        queries.add(templates_stat[0].format(device=dt))
    queries.add(templates_stat[1])
    queries.add(templates_stat[2])
    queries.add(templates_stat[3])
    queries.add(templates_stat[4])

    queries = {q.strip() for q in queries if q.strip()}
    return sorted(queries)


if __name__ == "__main__":
    queries = build_queries()
    print(f"Generated {len(queries)} test queries\n")

    categories = {
        "online_rate": [q for q in queries if "online rate" in q.lower()],
        "alert_trigger": [q for q in queries if any(kw in q.lower() for kw in
                         ["triggering", "alarm count", "alert count", "total alarm", "most frequently",
                          "alarm distribution", "hourly distribution", "peak time", "per device type"])],
        "offline": [q for q in queries if "offline" in q.lower()],
        "deployment": [q for q in queries if any(kw in q.lower() for kw in
                      ["deployed", "deployment", "distribution", "installation", "perimeter"])],
        "region_specific": [q for q in queries if any(kw in q.lower() for kw in
                          ["sensors deployed in", "sensors in ", "alarm events in ",
                           "how many cameras", "how many vibration", "how many electronic"])],
        "topk_ranking": [q for q in queries if "top " in q.lower()],
        "handling": [q for q in queries if any(kw in q.lower() for kw in
                    ["handling", "unresolved", "closure", "operator"])],
        "combined": [q for q in queries if any(kw in q.lower() for kw in
                    ["offline more than", "false alarm rate in", "between area"])],
        "time_series": [q for q in queries if any(kw in q.lower() for kw in
                       ["trend", "daily", "weekly", "hourly", "between ", "daytime", "nighttime",
                        "past week", "past month", "november", "response time"])],
        "statistical": [q for q in queries if any(kw in q.lower() for kw in
                       ["average", "correlation", "consistent", "false alarm rate",
                        "distribution by time", "frequency per"])],
    }

    for cat, qs in categories.items():
        print(f"\n{'='*60}")
        print(f"Category: {cat} ({len(qs)} queries)")
        print(f"{'='*60}")
        for q in qs[:5]:
            print(f"  - {q}")
        if len(qs) > 5:
            print(f"  ... and {len(qs)-5} more")

    output = {
        "total": len(queries),
        "categories": {cat: len(qs) for cat, qs in categories.items()},
        "queries": queries,
    }

    os.makedirs("experiments", exist_ok=True)
    with open("experiments/test_queries_100plus.json", "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)
    print(f"\n\nSaved to experiments/test_queries_100plus.json")
    print(f"Total queries: {len(queries)}")
